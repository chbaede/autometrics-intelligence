export interface QuarterlyStockDisclosurePoint {
  period: string; // '2024-Q1' | '2024-Q2' | '2024-Q3' | '2024-Q4' | '2025-Q1' | '2025-Q2' | '2025-Q3' | '2025-Q4' | '2026-Q1' | '2026-Q2' | '2026-Q3'
  disclosureDate: string; // YYYY-MM-DD (Official quarterly earnings release date)
  closePrice: number | null; // Closing stock price on disclosure date (null if scheduled/unreported)
  earningsDayChangePct: number | null; // 1-day stock reaction (%) on earnings release session
  deliveries: number | null; // Quarterly vehicle deliveries (thousand units)
  revenue: number | null; // Quarterly consolidated revenue (currency millions)
  operatingIncome: number | null; // Quarterly operating profit / EBIT (currency millions; Net profit for BYD Q3)
  operatingMargin: number | null; // Quarterly operating margin (%)
  isNetProfitBasis?: boolean; // True when profit represents Net Profit (e.g. BYD CASBE Q3)
  isScheduled?: boolean; // True when quarter earnings are scheduled in the future
  catalystKo: string;
  catalystEn: string;
}

