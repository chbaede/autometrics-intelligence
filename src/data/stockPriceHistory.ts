/**
 * Retrieves the stock price & earnings correlation profile for a given company,
 * dynamically synchronizing any period present in METRIC_OBSERVATIONS / SOURCE_DOCUMENTS
 * so that financial values and disclosure dates remain 100% consistent with canonical data.
 */
export function getCompanyStockHistory(companyId: string): CompanyStockHistoryProfile | undefined {
  const raw = RAW_STOCK_PROFILES[companyId];
  if (!raw) return undefined;

  const companyObs = getObservationsByCompany(companyId);
  const companySources = SOURCE_DOCUMENTS.filter((s) => s.companyId === companyId);

  const syncedPoints: QuarterlyStockDisclosurePoint[] = raw.points.map((pt) => {
    const scheduled = getScheduledDisclosure(companyId, pt.period);
    const matchingObs = companyObs.filter((o) => o.period === pt.period);
    const matchingSource = companySources.find((s) => s.period === pt.period);

    if (matchingObs.length === 0) {
      if (scheduled) {
        return {
          ...pt,
          disclosureDate: scheduled.scheduledDate,
          isScheduled: true,
        };
      }
      return {
        ...pt,
        disclosureDate: matchingSource?.publicationDate || pt.disclosureDate,
      };
    }

    const delObs = matchingObs.find((o) => o.metricId === 'deliveries_global');
    const revObs = matchingObs.find((o) => o.metricId === 'revenue');
    const ebitObs = matchingObs.find((o) => o.metricId === 'operating_income');
    const netObs = matchingObs.find((o) => o.metricId === 'net_income');
    const marginObs = matchingObs.find((o) => o.metricId === 'operating_margin');

    const isBydNet = companyId === 'byd' && !ebitObs && Boolean(netObs);
    const syncedProfit = ebitObs?.value ?? (isBydNet ? netObs?.value ?? pt.operatingIncome : pt.operatingIncome);
    const syncedRev = revObs?.value ?? pt.revenue;
    const syncedMargin =
      marginObs?.value ??
      (isBydNet && syncedProfit !== null && syncedRev
        ? Number(((syncedProfit / syncedRev) * 100).toFixed(1))
        : pt.operatingMargin);

    return {
      ...pt,
      disclosureDate: matchingSource?.publicationDate || pt.disclosureDate,
      deliveries: delObs?.value ?? pt.deliveries,
      revenue: syncedRev,
      operatingIncome: syncedProfit,
      operatingMargin: syncedMargin,
      isNetProfitBasis: isBydNet || pt.isNetProfitBasis,
      isScheduled: false,
    };
  });

  return {
    ...raw,
    points: syncedPoints,
  };
}

export function getAllCompanyStockHistories(): CompanyStockHistoryProfile[] {
  return Object.keys(RAW_STOCK_PROFILES)
    .map((id) => getCompanyStockHistory(id))
    .filter((p): p is CompanyStockHistoryProfile => Boolean(p));
}
